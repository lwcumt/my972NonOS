void Thai_Draw(unsigned short *tpic,int x,int y,unsigned short fcolor,unsigned char bflag,unsigned int bkcolor)
{
int i;
int j,m;
int w,h;
int col_cnt=0;
	

	unsigned short temp;
	pInt16U ptr;
	pInt16U  psr = tpic;
	w=*psr++;
	h=*psr++;
	
		ptr=(pInt16U)(LCD_VRAM_BASE_ADDR + (y*C_GLCD_H_SIZE + x )*2);

		
		for(j=0; j<h; j++)
			{
			col_cnt=0;
			for(i=0; i<w; i++)
				{	    
				temp = *psr++;
				for(m=0; m<16; m++)
					{
					if(temp&0x8000)		
						*ptr++ = fcolor;
					else
                    {
                        if(bflag==0)					
						ptr++;
						else
						*ptr++ = bkcolor;
					}
					temp<<=1;
					
					col_cnt++;
					if(col_cnt>=w)
						break;
					}
				if(col_cnt>=w)
					{
						col_cnt=0;
						break;
					}
				}
			y++;
			ptr=(pInt16U)(LCD_VRAM_BASE_ADDR + (y*C_GLCD_H_SIZE + x )*2);		
			}			
}


