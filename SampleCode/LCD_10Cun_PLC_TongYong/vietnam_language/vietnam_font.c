/**
 * @brief 在LCD上显示越南语字符
 * @param pic 字符点阵数据指针
 * @param x 显示起始x坐标
 * @param y 显示起始y坐标
 * @param fcolor 字符颜色
 * @param bflag 背景标志:0-透明背景,1-显示背景色
 * @param bkcolor 背景颜色
 * 
 * 函数逻辑:
 * 1. 从点阵数据中获取字符宽度和高度
 * 2. 按行扫描点阵数据,每8个点为一个字节,每个字节的8个位分别对应8个像素点,从低位到高位依次对应从左到右的像素点
 * 3. 根据点阵数据中的位值决定显示前景色还是背景色
 * 4. 支持透明背景和背景色显示两种模式
 */
void vietnam_print(unsigned char *pic,int x,int y,unsigned short fcolor,unsigned char bflag,unsigned int bkcolor)
{
    Int8U temp;
    Int16U wide,high,w,h, col_cnt;
    
	pInt16U ptr=(pInt16U)(LCD_VRAM_BASE_ADDR + (y*C_GLCD_H_SIZE + x )*2);
	pInt8U  psr = pic;
	wide=((Int16U)psr[0]<<8 )| psr[1];
	high=((Int16U)psr[2]<<8 )| psr[3];
    psr+= 4;
	
	for(h = 0; h < high; h++)
    {
        col_cnt = 0;
        for(w = 0; w < wide; w+=8)
        {
            temp = *psr++;
            for (Int8U i = 0; i < 8; i++)
            {
                if(temp & 0x01)
                {
                    *ptr++ = fcolor;
                }
                else
                {
                    if(bflag == 0)					
						ptr++;
					else
						*ptr++ = bkcolor;
                }
                temp >>= 1;
                col_cnt++;
                if(col_cnt>=wide)
                    break;
            }
            if(col_cnt>=wide)
                break;
        }
        y++;
        ptr=(pInt16U)(LCD_VRAM_BASE_ADDR + (y*C_GLCD_H_SIZE + x )*2);
    }
}
